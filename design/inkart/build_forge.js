// Builds src/forge_engine.js: the drawing core of PAPERFORGE (paperforge.html) without its editor UI, for the game's live hero sprites.
// It keeps every definition (catalog, body rig, gear layers, motion clips) and drops the top-level start-up code (build the UI, load a saved
// character, start the preview loop). The game gets window.CB_PF with the functions it needs.
// Usage (repo root): node design/inkart/build_forge.js   (then node build.js)
const fs = require('fs'), path = require('path');
const acorn = require(['/opt/node-tools/node_modules/acorn', '/opt/npm-tools/node_modules/acorn', 'acorn'].find((p) => { try { require.resolve(p); return true; } catch (e) { return false; } }));
const html = fs.readFileSync(path.join(__dirname, 'paperforge.html'), 'utf8');
const js = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map((m) => m[1]).sort((a, b) => b.length - a.length)[0];
const ast = acorn.parse(js, { ecmaVersion: 2022, sourceType: 'script' });
let out = '', last = 0, dropped = 0;
for (const n of ast.body) {
  const keep = n.type === 'FunctionDeclaration' || n.type === 'VariableDeclaration' || n.type === 'ClassDeclaration'
    || (n.type === 'ExpressionStatement' && n.directive === 'use strict');
  out += js.slice(last, n.start); if (keep) out += js.slice(n.start, n.end); else dropped++;
  last = n.end;
}
out += js.slice(last);
const EXPORTS = ['VERSION', 'CATALOG', 'CLIPS', 'SLOTS', 'ORDER', 'SKINS', 'SCHEMES', 'MOTION_W', 'MOTION_H', 'W', 'H', 'makeState', 'clone', 'applyPalette', 'invalidate', 'getItem',
  'compose', 'motionCompose', 'motionDimensions', 'poseAt', 'clipInfo', 'attackProfile', 'alphaBounds', 'mix', 'hash', 'colors'];
const have = EXPORTS.filter((k) => new RegExp('\\b' + k + '\\s*=|function\\s+' + k + '\\b').test(out));
const src = `// GENERATED by design/inkart/build_forge.js from design/inkart/paperforge.html (PAPERFORGE ${'$'}{VERSION}): its drawing core, no editor UI.\n`
  + `// Do not edit by hand: change paperforge.html (or src/forge.js for game-side behaviour) and re-run the build script.\n`
  + `(function () {\n${out}\n;window.CB_PF = { ${have.map((k) => k + ': typeof ' + k + " !== 'undefined' ? " + k + ' : undefined').join(', ')}, setState: (s) => { state = s; }, getState: () => state };\n})();\n`;
fs.writeFileSync(path.join(__dirname, '..', '..', 'src', 'forge_engine.js'), src.replace('${VERSION}', ''));
console.log('forge_engine.js', Math.round(src.length / 1024) + ' KB, dropped', dropped, 'start-up statements, exports', have.length + '/' + EXPORTS.length, EXPORTS.filter((k) => !have.includes(k)).join(' '));
