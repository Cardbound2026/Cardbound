// Measures what every gear stat is worth to every codex, by simulation. Writes src/statweights.js.
// For each codex, its three test decks fight every map's boss (made too tough to kill, so the fight runs a set number of rounds)
// with Green gear. Each stat is then bumped on its own and the fights replayed on the same seeds. "Fight strength" is
// rounds-to-die / rounds-to-kill = (max HP / HP lost per round) x (damage dealt per round); a stat's weight is how much one
// point of it moves log(fight strength). Usage (repo root): node tools/statvalue.js [seeds=3] [codexKey ...]   (~10-20 min for all)
const fs = require('fs'), path = require('path');
const S = path.join(__dirname, '..', 'src');
const src = fs.readFileSync(path.join(S, 'data.js'), 'utf8'); const D = JSON.parse(src.slice(src.indexOf('{'), src.lastIndexOf('}') + 1));
global.window = global.window || {}; require(path.join(S, 'testdecks.js')); const TD = window.CB_TESTDECKS;
const CB = require(path.join(S, 'engine.js')); CB.gearData(D); const { autopilot } = require('./autopilot.js');
const SEEDS = +(process.argv[2] || 3), ONLY = process.argv.slice(3), LEVEL = 2, ROUNDS = 10, ELS = ['Fire', 'Frost', 'Nature', 'Arcane', 'Shadow', 'Holy'];
// each bump: [weight key, size, how to apply it to the player at the start of the fight]
const BUMPS = [
  ['hp', 0, null], // max HP is valued by the log rule below, not by a bump
  ['strength', 10, (p, n) => { p.strength += n; }], ['intelligence', 10, (p, n) => { p.intelligence += n; }], ['dexterity', 10, (p, n) => { p.dexterity += n; }], ['spirit', 10, (p, n) => { p.spirit += n; }],
  ['crit', 8, (p, n) => { p.crit += n; }], ['critDmg', 25, (p, n) => { p.critMult += n / 100; }], ['init', 6, (p, n) => { p.baseInit += n; }],
  ['maxMana', 25, (p, n) => { p.maxMana += n; }], ['regen', 5, (p, n) => { p.regen += n; }], ['draw', 1, (p, n) => { p.draw += n; }],
  ['multiHit', 8, (p, n) => { p.multiHit += n; }], ['multiplay', 8, (p, n) => { p.multiplay += n; }], ['multicast', 8, (p, n) => { p.multicast += n; }], ['bleedChance', 8, (p, n) => { p.bleedChance += n; }],
  ['lifesteal', 6, (p, n) => { p.lifesteal += n; }], ['thorns', 4, (p, n) => { p.thorns += n; }], ['recovery', 4, (p, n) => { p.recovery += n; }], ['weaponDmg', 3, (p, n) => { p.weaponDmg += n; }],
  ['resist', 15, (p, n, el) => { p.resist[el] = Math.min(75, (p.resist[el] || 0) + n); }],
  ...ELS.map((el) => ['elem:' + el, 15, (p, n) => { p.elem[el] = (p.elem[el] || 0) + n; }]),
];
const BOSSES = Object.values(D.maps).map((m) => [m.boss, m.element]);
function fightOnce(deck, bump, boss, el, seed) {
  const gear = CB.presetGear(deck.cls, 'Green').concat([CB.makeCodex(D, CB.makeRng(7), deck.codex, LEVEL)]);
  const cb = new CB.Combat({ party: [{ cls: deck.cls, deck: deck.cards, gear }], enemies: [boss], level: LEVEL, seed, data: D });
  const p = cb.players[0]; if (bump && bump[2]) bump[2](p, bump[1], el);
  for (const e of cb.enemies) { e.maxHp *= 40; e.hp = e.maxHp; }
  const hp0 = p.maxHp; let g = 0;
  while (!cb.over && cb.round <= ROUNDS && g++ < 3000) { if (cb.phase === 'enemy') cb.runEnemies(); else autopilot(cb); }
  const dealt = cb.enemies.reduce((s, e) => s + (e.maxHp - Math.max(0, e.hp)), 0), lost = hp0 - Math.max(0, p.dead ? 0 : p.hp);
  return { dealt, lost, rounds: Math.min(cb.round, ROUNDS), hp: hp0 };
}
function strength(deck, bump) { // log fight strength over every boss and seed
  let dealt = 0, lost = 0, rounds = 0, hp = 0;
  for (const [boss, el] of BOSSES) for (let s = 1; s <= SEEDS; s++) { const r = fightOnce(deck, bump, boss, el, s * 7919 + 17); dealt += r.dealt; lost += r.lost; rounds += r.rounds; hp = r.hp; }
  return Math.log(dealt / rounds) - Math.log(Math.max(lost, 0.03 * hp * rounds) / rounds);
}
const out = {}; const codexes = [...new Set(TD.map((d) => d.codex))].filter((k) => !ONLY.length || ONLY.includes(k));
for (const cx of codexes) {
  const decks = TD.filter((d) => d.codex === cx), w = {};
  for (const deck of decks) {
    const base = strength(deck, null);
    for (const b of BUMPS) if (b[2]) w[b[0]] = (w[b[0]] || 0) + Math.max(0, (strength(deck, b) - base) / b[1]) / decks.length; // a stat never counts as harmful
  }
  w.hp = 1; // log(max HP): doubling HP doubles rounds-to-die
  for (const k of Object.keys(w)) w[k] = +w[k].toPrecision(3);
  out[cx] = w; console.error(cx, JSON.stringify(w));
}
if (!ONLY.length) {
  const file = path.join(S, 'statweights.js');
  fs.writeFileSync(file, `// GENERATED by tools/statvalue.js: what one point of each gear stat is worth to each codex (change in log fight strength).\n// Re-run it after big balance changes: node tools/statvalue.js\n(function (r) {\n  const W = ${JSON.stringify(out)};\n  if (typeof module !== 'undefined' && module.exports) module.exports = W; else r.CB_STATW = W;\n})(typeof window !== 'undefined' ? window : globalThis);\n`);
  console.error('wrote', file);
} else console.log(JSON.stringify(out));
